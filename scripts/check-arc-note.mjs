// Uses the browser WASM shipped with the pinned SDK, not the native Node binding.
import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import ts from "typescript";
const sdkDir = new URL("../node_modules/@miden-sdk/miden-sdk/dist/st/", import.meta.url);
const glue = (await readdir(sdkDir)).find(name => /^Cargo-.*\.js$/.test(name));
assert.ok(glue, "SDK WASM glue not found; update this check for the new SDK layout.");
const sdk = await import(new URL(glue, sdkDir).href);
sdk.initSync({ module: await readFile(new URL("assets/miden_client_web.wasm", sdkDir)) });
const source = await readFile(new URL("../src/bridge/providers/xreserve/delivery.ts", import.meta.url), "utf8");
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { deriveArcNoteId } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
// Independently generated by fixtures/arc-note-reference using Rust standards/protocol 0.17.1.
const intent = {
  amount: "1000000", recipient: "0x4e6fb40fd2f6a55140df2c42dfb5b7",
  faucet: "0x4cbdcaffe75f0a317482224dae6436", sender: "0x898362f24c366fdf7bb164c40a9127cc9f5119b6",
  nonce: "0xabab9dfff95292a7b7ff97b193c2f17ac361ca98e3b9f15fed8d508795fc4220",
};
const expected = "0xc8ee349db41b2d9296564360ec5d0f9f72654a4c8238b74dcf21861a7a4ef2a5";
for (let i = 0; i < 3; i++) assert.equal(deriveArcNoteId(intent, sdk), expected);
assert.notEqual(deriveArcNoteId({ ...intent, nonce: `0x${"00".repeat(32)}` }, sdk), expected);
assert.notEqual(deriveArcNoteId({ ...intent, amount: "2000000" }, sdk), expected);
console.log("Arc expected note: browser WASM matches independent Rust 0.17.1 reference.");
